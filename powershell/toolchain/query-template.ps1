<#
.SYNOPSIS
  AI-facing query helper for the local-toolchain skill.
.DESCRIPTION
  Generated file. Reads only inventory.json next to this script.
  Do not edit by hand; this file is generated by the toolchain generator.
#>
param(
  [Parameter(Position = 0)]
  [ValidateSet('list', 'find', 'config', 'doctor', 'summary', 'help')]
  [string]$Command = 'list',
  [Parameter(Position = 1)]
  [string]$Query = '',
  [switch]$Json
)

$ErrorActionPreference = 'Stop'
$InventoryPath = Join-Path $PSScriptRoot 'inventory.json'

if (-not (Test-Path -LiteralPath $InventoryPath)) {
  Write-Error "Missing inventory.json beside query.ps1: $InventoryPath"
  exit 1
}

$Inventory = Get-Content -LiteralPath $InventoryPath -Raw -Encoding UTF8 | ConvertFrom-Json
$QueryHint = 'pwsh.exe -NoProfile -File "' + $PSCommandPath + '"'

function Get-Matches {
  param([string]$Term)
  $q = $Term.ToLowerInvariant()
  return @($Inventory.tools | Where-Object {
    $haystack = (@($_.id, $_.name, $_.category, $_.command, $_.path, $_.notes) + @($_.tags)) -join ' '
    $haystack.ToLowerInvariant().Contains($q)
  })
}

switch ($Command) {
  'list' {
    if ($Json) { $Inventory.tools | ConvertTo-Json -Depth 10; break }
    Write-Host ("Inventory: {0} tools | generated {1}" -f $Inventory.summary.total, $Inventory.generated_at)
    $Inventory.tools | Sort-Object category, id | Select-Object id, name, category, version, status, path | Format-Table -AutoSize -Wrap
  }
  'find' {
    if (-not $Query) { Write-Host "Usage: $QueryHint find <query>"; break }
    $matches = Get-Matches $Query
    if ($Json) { $matches | ConvertTo-Json -Depth 10; break }
    Write-Host ("Matches for '{0}': {1}" -f $Query, $matches.Count)
    $matches | Sort-Object category, id | Select-Object id, name, category, version, status, path | Format-Table -AutoSize -Wrap
  }
  'config' {
    if ($Json) { $Inventory.config_facts | ConvertTo-Json -Depth 10; break }
    $Inventory.config_facts | Select-Object id, title, value, usage | Format-Table -AutoSize -Wrap
  }
  'doctor' {
    $required = @('node','npm','npx','go','dotnet','uv','uvx','git','gh','pwsh','opencode','rea-mcp','rea-skill','java-jdk25','objdump','wabt','rizin','tshark','capinfos','apktool-3','ilspycmd')
    $map = @{}
    foreach ($t in $Inventory.tools) { $map[$t.id] = $t }
    $problems = 0
    foreach ($id in $required) {
      if (-not $map.ContainsKey($id) -or $map[$id].status -ne 'installed') {
        Write-Host "MISSING  $id"
        $problems++
      } else {
        Write-Host "OK       $id  $($map[$id].version)"
      }
    }
    Write-Host ''
    Write-Host "Doctor: $problems problem(s). Missing entries may be optional on this host."
    exit $(if ($problems -gt 0) { 1 } else { 0 })
  }
  'summary' {
    $Inventory.summary | ConvertTo-Json -Depth 8
  }
  'help' {
    @"
Usage:
  $QueryHint list             List all tools
  $QueryHint find <query>     Filter by id/name/category/path/tag/notes
  $QueryHint config           Show configuration facts
  $QueryHint doctor           Check core tools
  $QueryHint summary          Show summary JSON
  $QueryHint help             Show this help

Add -Json to list/find/config for JSON output.
Reads only inventory.json beside this script. No source directory is needed.
"@ | Write-Host
  }
}
