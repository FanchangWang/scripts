#!/usr/bin/env bash
# Install FREE REA-supported tools on Linux and generate ~/.local/bin/rea-mcp.
# Paid tools (IDA, JEB, Hopper) are intentionally skipped.
set -u
HOME_DIR="${HOME:-/home/guyue}"
BIN="$HOME_DIR/.local/bin"
TOOLS="$HOME_DIR/code-tools"
REV="$TOOLS/reverse"
PROXY_URL="http://192.168.31.50:7890"
mkdir -p "$BIN" "$TOOLS" "$REV" "$TOOLS/browser" "$TOOLS/dotnet-tools"

curl_p() { env http_proxy="$PROXY_URL" https_proxy="$PROXY_URL" HTTP_PROXY="$PROXY_URL" HTTPS_PROXY="$PROXY_URL" curl --retry 3 --retry-delay 2 -fsSL "$@"; }
get_asset() { # url, out: GitHub accelerator first ("base/https://github.com/..."), then direct, then proxy
  local url="$1" out="$2"
  case "$url" in
    https://github.com/*)
      local accel="https://github.allproxy.dpdns.org/$url"
      curl -fsSL --retry 2 -o "$out" "$accel" \
        || curl -fsSL --retry 2 -o "$out" "$url" \
        || curl_p -o "$out" "$url" ;;
    *)
      curl -fsSL --retry 2 -o "$out" "$url" || curl_p -o "$out" "$url" ;;
  esac
}
step() { printf '\n===== %s =====\n' "$1"; }
fail() { printf 'FAILED: %s (continuing)\n' "$1"; }
latest_tag() {
  curl_p "https://api.github.com/repos/$1/releases/latest" 2>/dev/null \
    | python3 -c 'import json,sys; print(json.load(sys.stdin)["tag_name"])' 2>/dev/null || echo ""
}

step "Ghidra (free, needs JDK25)"
GHIDRA_DIR="$REV/ghidra/12.2.0"
if [ ! -x "$GHIDRA_DIR/support/analyzeHeadless" ]; then
  GHIDRA_VER="$(latest_tag NationalSecurityAgency/ghidra)"
  GHIDRA_VER="${GHIDRA_VER:-Ghidra_12.2_build}"
  GHIDRA_ZIP="$(curl_p "https://api.github.com/repos/NationalSecurityAgency/ghidra/releases/latest" 2>/dev/null \
    | python3 -c 'import json,sys; d=json.load(sys.stdin); print(next(a["name"] for a in d["assets"] if a["name"].endswith(".zip")))' 2>/dev/null)"
  GHIDRA_ZIP="${GHIDRA_ZIP:-ghidra_12.2_PUBLIC_20261016.zip}"
  mkdir -p /tmp/ghidra
  get_asset "https://github.com/NationalSecurityAgency/ghidra/releases/download/${GHIDRA_VER}/${GHIDRA_ZIP}" /tmp/ghidra/g.zip \
    && unzip -q -o /tmp/ghidra/g.zip -d /tmp/ghidra \
    && mkdir -p "$GHIDRA_DIR" \
    && cp -a /tmp/ghidra/ghidra_12.2_PUBLIC/. "$GHIDRA_DIR/" \
    || fail "Ghidra download"
fi
[ -d "$GHIDRA_DIR" ] && echo "GHIDRA_INSTALL_DIR=$GHIDRA_DIR"

step "jadx-headless-mcp (free)"
JMCP="$REV/jadx-headless-mcp/jadx-headless-mcp-0.8.0-all.jar"
if [ ! -f "$JMCP" ]; then
  mkdir -p "$(dirname "$JMCP")"
  get_asset \
    'https://github.com/1013503897/jadx-headless-mcp/releases/download/v0.8.0/jadx-headless-mcp-0.8.0-all.jar' \
    "$JMCP" || fail "jadx-headless-mcp download"
fi
[ -f "$JMCP" ] && echo "REA_JADX_MCP_JAR=$JMCP"

step "rizin static (free)"
RIZIN="$(command -v rizin 2>/dev/null || echo "$REV/rizin/0.9.1/bin/rizin")"
if [ ! -x "$RIZIN" ]; then
  mkdir -p "$REV/rizin/0.9.1"
  get_asset \
    'https://github.com/rizinorg/rizin/releases/download/v0.9.1/rizin-v0.9.1-static-x86_64.tar.xz' \
    /tmp/rizin.tar.xz \
    && tar -xJf /tmp/rizin.tar.xz -C "$REV/rizin/0.9.1" --strip-components=1 \
    || fail "rizin download"
fi
[ -x "$RIZIN" ] && echo "REA_RIZIN_COMMAND=$RIZIN"

step "Chrome for Testing (free)"
CHROME="$TOOLS/browser/chrome-linux64/chrome"
if [ ! -x "$CHROME" ]; then
  CHROME_VER="$(curl_p https://googlechromelabs.github.io/chrome-for-testing/last-known-good-versions.json \
    | python3 -c 'import json,sys; print(json.load(sys.stdin)["channels"]["Stable"]["version"])' 2>/dev/null)"
  if [ -n "$CHROME_VER" ]; then
    curl -fsSL --retry 2 -o /tmp/chrome.zip \
      "https://storage.googleapis.com/chrome-for-testing-public/${CHROME_VER}/linux64/chrome-linux64.zip" \
      || curl_p -o /tmp/chrome.zip \
      "https://storage.googleapis.com/chrome-for-testing-public/${CHROME_VER}/linux64/chrome-linux64.zip" \
      || fail "chrome download"
    [ -f /tmp/chrome.zip ] && unzip -q -o /tmp/chrome.zip -d "$TOOLS/browser" || true
  else
    fail "chrome version lookup"
  fi
fi
[ -x "$CHROME" ] && echo "REA_BROWSER_EXECUTABLE=$CHROME"

step ".NET SDK + ilspycmd (free)"
DOTNET="$TOOLS/dotnet/dotnet"
if [ ! -x "$DOTNET" ]; then
  curl_p -o /tmp/dotnet-install.sh https://dot.net/v1/dotnet-install.sh \
    && env http_proxy="$PROXY_URL" https_proxy="$PROXY_URL" \
       bash /tmp/dotnet-install.sh --channel LTS --install-dir "$TOOLS/dotnet" \
    || fail "dotnet sdk"
fi
if [ -x "$DOTNET" ] && [ ! -x "$TOOLS/dotnet-tools/ilspycmd" ]; then
  env DOTNET_ROOT="$TOOLS/dotnet" PATH="$TOOLS/dotnet:$PATH" \
    "$DOTNET" tool install --tool-path "$TOOLS/dotnet-tools" ilspycmd \
    || fail "ilspycmd"
fi
[ -x "$TOOLS/dotnet-tools/ilspycmd" ] && echo "REA_ILSPY_CMD_PATH=$TOOLS/dotnet-tools/ilspycmd"

step "generate ~/.local/bin/rea-mcp wrapper"
WRAP="$BIN/rea-mcp"
{
  echo '#!/usr/bin/env bash'
  echo '# REA MCP wrapper (Linux) — generated by toolchain/rea-setup.sh'
  echo '# Only FREE tools are configured. Paid tools (IDA / JEB / Hopper) are skipped.'
  echo 'export JAVA_HOME="$HOME/code-tools/jdk-25"'
  [ -x "$GHIDRA_DIR/support/analyzeHeadless" ] && echo "export GHIDRA_INSTALL_DIR=\"$GHIDRA_DIR\""
  [ -x /usr/bin/objdump ] && echo 'export REA_OBJDUMP_COMMAND=/usr/bin/objdump'
  [ -x "$RIZIN" ] && echo "export REA_RIZIN_COMMAND=\"$RIZIN\""
  [ -x /usr/bin/wasm-objdump ] && echo 'export REA_WABT_BIN_DIRECTORY=/usr/bin'
  [ -x /usr/bin/tshark ] && echo 'export REA_TSHARK_COMMAND=/usr/bin/tshark'
  [ -x /usr/bin/capinfos ] && echo 'export REA_CAPINFOS_COMMAND=/usr/bin/capinfos'
  [ -f "$JMCP" ] && echo "export REA_JADX_MCP_JAR=\"$JMCP\""
  [ -x "$BIN/apktool" ] && echo "export REA_APKTOOL_COMMAND=\"$BIN/apktool\""
  [ -x "$HOME_DIR/code-tools/android-sdk/platform-tools/adb" ] && \
    echo "export REA_ADB_PATH=\"$HOME_DIR/code-tools/android-sdk/platform-tools/adb\""
  [ -x "$TOOLS/dotnet-tools/ilspycmd" ] && \
    echo "export REA_ILSPY_CMD_PATH=\"$TOOLS/dotnet-tools/ilspycmd\""
  [ -x "$CHROME" ] && echo "export REA_BROWSER_EXECUTABLE=\"$CHROME\""
  echo '# Kuna: Windows-only build per REA docs; skipped on Linux.'
  echo "exec \"$HOME_DIR/code-tools/nodejs/bin/npx\" -y rea-agents@latest mcp \"\$@\""
} > "$WRAP"
chmod +x "$WRAP"
echo "wrapper: $WRAP"
grep -E '^(export|exec)' "$WRAP"
