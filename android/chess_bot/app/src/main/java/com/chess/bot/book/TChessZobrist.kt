    private val table: LongArray by lazy {
        val hex = TABLE_HEX.filterNot { it.isWhitespace() }
        LongArray(14 * 256) { i ->
            java.lang.Long.parseUnsignedLong(
                hex.substring(
                    i * 16,
                    i * 16 + 16
                ), 16
            )
        }
    }

    /** 计算局面 vkey；mirror=true 时按左右镜像后的坐标计算（查询兵河库的镜像通道）。 */
    fun zobrist(board: Board, redGo: Boolean, mirror: Boolean = false): Long {
        var z = 0L
        for (y in 0 until 10) {
            for (x in 0 until 9) {
                val piece = board[y][x] ?: continue
                val idx = pieceIndex[piece] ?: continue
                val col = if (mirror) 8 - x else x
                z = z xor table[idx * 256 + c90[y * 9 + col]]
            }
        }
        if (redGo) z = z xor ZOBRIST_PLAYER
        return z
    }

    /** vmove -> ICCS 着法串（如 43687 -> "h2e2"）；viaMirror 命中时把列镜像回来。 */
    fun vmoveToIccs(vmove: Int, viaMirror: Boolean): String? {
        var from = vmove shr 8
        var to = vmove and 0xFF
        if (viaMirror) {
            from = mirrorSq(from); to = mirrorSq(to)
        }
        return coordMap[from]?.let { f -> coordMap[to]?.let { t -> f + t } }
    }

    /** ICCS 着法 -> vmove；mirror=true 时把列镜像过去。 */
    fun iccsToVmove(iccs: String, mirror: Boolean): Int? {
        if (iccs.length < 4) return null
        var from =
            coordMap.entries.firstOrNull { it.value == iccs.substring(0, 2) }?.key ?: return null
        var to =
            coordMap.entries.firstOrNull { it.value == iccs.substring(2, 4) }?.key ?: return null
        if (mirror) {
            from = mirrorSq(from); to = mirrorSq(to)
        }
        return (from shl 8) or to
    }

    /** 16x16 格号左右镜像：保留高 4 位（行），低 4 位（列）换为 14-列（col+3 -> 11-col，即 8-col+3）。 */
    private fun mirrorSq(sq: Int): Int = (sq and 0xF0) or (14 - sq % 16)
